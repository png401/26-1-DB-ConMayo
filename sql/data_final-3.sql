-- venue1 예술의전당 (10행×10열 = 100석, VIP:1~3행, R:4~6행, S:7~10행)
INSERT INTO seat (venue_id, section, row_num, col_num)
WITH RECURSIVE R AS (SELECT 1 AS n UNION ALL SELECT n+1 FROM R WHERE n < 10),
               C AS (SELECT 1 AS n UNION ALL SELECT n+1 FROM C WHERE n < 10)
SELECT 1, CASE WHEN R.n <= 3 THEN 'VIP' WHEN R.n <= 6 THEN 'R' ELSE 'S' END, R.n, C.n
FROM R CROSS JOIN C;

-- venue2 세종문화회관 (12행×8열 = 96석, VIP:1~4행, R:5~8행, A:9~12행)

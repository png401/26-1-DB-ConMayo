WITH RECURSIVE R AS (SELECT 1 AS n UNION ALL SELECT n+1 FROM R WHERE n < 12),
               C AS (SELECT 1 AS n UNION ALL SELECT n+1 FROM C WHERE n < 8)
SELECT 2, CASE WHEN R.n <= 4 THEN 'VIP' WHEN R.n <= 8 THEN 'R' ELSE 'A' END, R.n, C.n
FROM R CROSS JOIN C;

